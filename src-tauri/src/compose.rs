//! The Docker Compose file that describes one instance's containers.
//!
//! It is generated from the recipe, never hand-edited: WorldStone rewrites it whenever it needs
//! it, so what runs is always what the recipe and the instance's folders say. Everything in it is
//! per instance (project name, container names, volumes), so several instances never collide.
//! Paths are relative to the file itself, so no absolute path is baked in and a folder name with
//! spaces cannot break the file.

use crate::{
    builder, config, extractor,
    paths::InstancePaths,
    recipe::{DatabaseEngine, DatabaseMethod, Recipe, ServiceSpec},
};
use std::path::PathBuf;

/// The service that runs the database server.
pub const DATABASE_SERVICE: &str = "database";
/// Credentials the database container reads, in `Config/`.
pub const DATABASE_ENV_FILE: &str = "database.env";
/// Where the SQL repository and the backups folder appear inside the database container.
pub const SQL_MOUNT: &str = "/worldstone/sql";
pub const BACKUP_MOUNT: &str = "/worldstone/backups";
/// The port MariaDB listens on inside the instance's network. It is never published on the host.
pub const DATABASE_PORT: u16 = 3306;
/// Where the servers' ports are published on the host: this machine only, until the person
/// chooses to open the server to the network.
pub const HOST_ADDRESS: &str = "127.0.0.1";

pub fn project_name(instance: &str) -> String {
    format!("worldstone-{instance}")
}

pub fn database_container(instance: &str) -> String {
    format!("{}-db", project_name(instance))
}

pub fn database_volume(instance: &str) -> String {
    format!("{}-dbdata", project_name(instance))
}

/// The temporary container that runs the emulator's database importer.
pub fn import_container(instance: &str) -> String {
    format!("{}-import", project_name(instance))
}

/// The network the project's containers share; the importer joins it to reach the database.
pub fn network_name(instance: &str) -> String {
    format!("{}_default", project_name(instance))
}

/// The instance's configuration folders one service sees, as `(folder inside Config/server or an
/// empty text for the folder itself, where it appears in the container)`. Files a server insists on
/// finding in a folder of its own (the modules') are mounted there as well.
pub fn config_folders(recipe: &Recipe, service: &ServiceSpec) -> Vec<(String, String)> {
    let mut out = vec![(String::new(), recipe.run.config_mount.clone())];
    for file in recipe.config.files.iter().filter(|f| f.service.as_deref() == Some(service.id.as_str())) {
        if let (Some(folder), Some(mount)) = (&file.folder, &file.mount) {
            let entry = (folder.clone(), format!("{}/{mount}", recipe.build.install_prefix));
            if !out.contains(&entry) {
                out.push(entry);
            }
        }
    }
    out
}

/// The container of one of the recipe's services, such as `worldstone-mangos-zero-mangosd`.
pub fn service_container(instance: &str, service: &str) -> String {
    format!("{}-{service}", project_name(instance))
}

pub fn file(paths: &InstancePaths) -> PathBuf {
    paths.docker.join("compose.yaml")
}

/// A YAML double-quoted scalar. JSON strings are valid YAML, so nothing can break out of one.
fn q(text: &str) -> String {
    serde_json::to_string(text).expect("a string is always valid JSON")
}

/// What "ready" means for the database: the real server, listening on the network, not the
/// temporary one each image runs while it initialises a new data folder.
fn healthcheck_test(engine: DatabaseEngine) -> String {
    let command: &[&str] = match engine {
        DatabaseEngine::Mariadb => &["healthcheck.sh", "--connect", "--innodb_initialized"],
        // The temporary server has networking off, so a TCP ping only answers from the real one.
        // `ping` succeeds even when the login is refused: the server is up, which is all this asks.
        DatabaseEngine::Mysql => &["mysqladmin", "ping", "-h", "127.0.0.1", "--silent"],
    };
    let mut items = vec![q("CMD")];
    items.extend(command.iter().map(|part| q(part)));
    format!("[{}]", items.join(", "))
}

pub fn render(recipe: &Recipe, instance: &str) -> String {
    let db = &recipe.database;
    let project = project_name(instance);
    // Only the scripts method reads the SQL repository; the import tool has it in the image.
    let sql_repo = (db.method == DatabaseMethod::Scripts).then(|| recipe.repo_folder(recipe.database_repo()));
    let mut out = String::new();
    let mut line = |text: String| {
        out.push_str(&text);
        out.push('\n');
    };
    line("# Generated by WorldStone from the recipe. Changes made here are overwritten.".into());
    line(format!("name: {}", q(&project)));
    line("services:".into());
    line(format!("  {DATABASE_SERVICE}:"));
    line(format!("    image: {}", q(&builder::database_image(instance, recipe))));
    // Named locally from the public image by the database step; never fetched under this name.
    line("    pull_policy: never".into());
    line(format!("    container_name: {}", q(&database_container(instance))));
    // The app starts and stops the server itself; nothing should come back on its own after a
    // reboot without the person having asked for it.
    line("    restart: \"no\"".into());
    line("    env_file:".into());
    line(format!("      - {}", q(&format!("../Config/{DATABASE_ENV_FILE}"))));
    if !db.server_args.is_empty() {
        line("    command:".into());
        for arg in &db.server_args {
            line(format!("      - {}", q(arg)));
        }
    }
    line("    volumes:".into());
    line("      - type: volume".into());
    line("        source: dbdata".into());
    line("        target: /var/lib/mysql".into());
    if let Some(repo) = &sql_repo {
        line("      - type: bind".into());
        line(format!("        source: {}", q(&format!("../Repos/{repo}"))));
        line(format!("        target: {}", q(SQL_MOUNT)));
        line("        read_only: true".into());
        line("        bind:".into());
        line("          create_host_path: false".into());
    }
    line("      - type: bind".into());
    line("        source: \"../Backups\"".into());
    line(format!("        target: {}", q(BACKUP_MOUNT)));
    // Ready means the real server, listening and with InnoDB up, not the temporary one the
    // image runs while it initialises a new data folder.
    line("    healthcheck:".into());
    line(format!("      test: {}", healthcheck_test(db.engine)));
    line("      interval: 5s".into());
    line("      timeout: 5s".into());
    line("      retries: 60".into());
    line("      start_period: 10s".into());
    line("    labels:".into());
    line(format!("      io.worldstone.instance: {}", q(instance)));
    for service in &recipe.run.services {
        let file = recipe.config.files.iter().find(|f| f.id == service.config).expect("validated on load");
        let config_path = format!("{}/{}", recipe.run.config_mount, file.file_name());
        line(format!("  {}:", service.id));
        line(format!("    image: {}", q(&builder::image_ref(instance, recipe, service))));
        // The image is built here, never taken from a registry: a missing one is an error the
        // app explains, not a download of someone else's image under the same name.
        line("    pull_policy: never".into());
        line(format!("    container_name: {}", q(&service_container(instance, &service.id))));
        line("    restart: \"no\"".into());
        line(format!("    working_dir: {}", q(&recipe.run.config_mount)));
        line("    command:".into());
        line(format!("      - {}", q(&format!("{}/{}", recipe.build.install_prefix, service.binary))));
        for arg in &service.args {
            line(format!("      - {}", q(&arg.replace("{config}", &config_path))));
        }
        if service.console {
            line("    stdin_open: true".into());
        }
        line(format!("    stop_grace_period: {}", q(&format!("{}s", service.stop_grace_secs))));
        line("    depends_on:".into());
        line(format!("      {DATABASE_SERVICE}:"));
        line("        condition: service_healthy".into());
        line("    ports:".into());
        line(format!("      - {}", q(&format!("{HOST_ADDRESS}:{0}:{0}", service.port))));
        line("    volumes:".into());
        let mut mounts: Vec<(String, String, bool)> = config_folders(recipe, service)
            .into_iter()
            .map(|(folder, target)| match folder.is_empty() {
                true => (format!("../Config/{}", config::CONFIG_FOLDER), target, true),
                false => (format!("../Config/{}/{folder}", config::CONFIG_FOLDER), target, true),
            })
            .collect();
        mounts.push((format!("../Logs/{}", config::LOGS_FOLDER), recipe.run.logs_mount.clone(), false));
        for (source, target, read_only) in &mounts {
            let (source, target, read_only) = (source.as_str(), target.as_str(), *read_only);
            line("      - type: bind".into());
            line(format!("        source: {}", q(source)));
            line(format!("        target: {}", q(target)));
            if read_only {
                line("        read_only: true".into());
            }
            line("        bind:".into());
            line("          create_host_path: false".into());
        }
        if service.data {
            line("      - type: volume".into());
            line("        source: gamedata".into());
            line(format!("        target: {}", q(&recipe.run.data_mount)));
            line("        read_only: true".into());
        }
        // Healthy once the port accepts connections. The world server only listens after the
        // world has finished loading, so this is also how the app knows it is ready.
        line("    healthcheck:".into());
        line(format!(
            "      test: [\"CMD\", \"bash\", \"-c\", {}]",
            q(&format!("exec 3<>/dev/tcp/127.0.0.1/{}", service.port))
        ));
        line("      interval: 5s".into());
        line("      timeout: 5s".into());
        line("      retries: 360".into());
        line("      start_period: 20s".into());
        line("    labels:".into());
        line(format!("      io.worldstone.instance: {}", q(instance)));
    }
    line("volumes:".into());
    line("  dbdata:".into());
    line(format!("    name: {}", q(&database_volume(instance))));
    line("    labels:".into());
    line(format!("      io.worldstone.instance: {}", q(instance)));
    // Created by the extraction step. Declared external so that Compose never creates it empty
    // and never removes it: a start without extracted data fails instead of running on nothing.
    line("  gamedata:".into());
    line(format!("    name: {}", q(&extractor::volume_name(instance))));
    line("    external: true".into());
    out
}

/// Writes the file for this instance, leaving it untouched when it is already right.
pub fn write(paths: &InstancePaths, recipe: &Recipe, instance: &str) -> Result<PathBuf, String> {
    let path = file(paths);
    let text = render(recipe, instance);
    if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        std::fs::create_dir_all(&paths.docker).map_err(|e| format!("Cannot create {}: {e}", paths.docker.display()))?;
        std::fs::write(&path, text).map_err(|e| format!("Cannot write {}: {e}", path.display()))?;
    }
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn zero() -> Recipe {
        crate::recipe::builtin().unwrap().remove(0)
    }

    #[test]
    fn everything_is_named_per_instance() {
        let text = render(&zero(), "mangos-zero");
        assert!(text.contains("name: \"worldstone-mangos-zero\""));
        assert!(text.contains("container_name: \"worldstone-mangos-zero-db\""));
        assert!(text.contains("name: \"worldstone-mangos-zero-dbdata\""));
        let other = render(&zero(), "second");
        assert!(other.contains("container_name: \"worldstone-second-db\"") && !other.contains("mangos-zero"));
    }

    #[test]
    fn the_sql_is_mounted_read_only_and_only_where_it_exists() {
        let text = render(&zero(), "mangos-zero");
        assert!(text.contains("source: \"../Repos/mangoszero-database\""));
        assert!(text.contains("read_only: true"), "the scripts must not be writable from the container");
        assert!(text.contains("create_host_path: false"), "a missing repository is an error, not an empty folder");
    }

    #[test]
    fn each_engine_is_asked_whether_the_real_server_is_up_in_its_own_way() {
        let zero = render(&zero(), "mangos-zero");
        assert!(zero.contains(r#"test: ["CMD", "healthcheck.sh", "--connect", "--innodb_initialized"]"#), "{zero}");
        let ac = crate::recipe::builtin().unwrap().into_iter().find(|r| r.id == "azerothcore").unwrap();
        let text = render(&ac, "azerothcore");
        assert!(text.contains(r#"test: ["CMD", "mysqladmin", "ping", "-h", "127.0.0.1", "--silent"]"#), "{text}");
        assert!(!text.contains("healthcheck.sh") && text.contains("worldstone/wotlk-database:8.4"), "{text}");
    }

    #[test]
    fn no_secret_and_no_absolute_path_is_written_into_the_file() {
        let text = render(&zero(), "mangos-zero");
        assert!(!text.to_lowercase().contains("password"));
        assert!(text.contains("../Config/database.env"));
        assert!(!text.contains(":\\") && !text.contains("C:/"), "{text}");
    }

    /// The lines of one service, from its header to the next key at the same or a lower level.
    fn section(text: &str, service: &str) -> String {
        let header = format!("  {service}:\n");
        let start = text.find(&header).unwrap_or_else(|| panic!("no {service} in\n{text}"));
        let mut lines = text[start..].split_inclusive('\n');
        let mut out = String::from(lines.next().unwrap());
        for line in lines.take_while(|l| l.starts_with("    ")) {
            out.push_str(line);
        }
        out
    }

    #[test]
    fn the_database_is_not_published_on_a_host_port() {
        let text = render(&zero(), "mangos-zero");
        assert!(!section(&text, "database").contains("ports:") && !text.contains("3306:"));
    }

    #[test]
    fn each_server_is_a_container_on_the_built_image_that_is_never_pulled() {
        let text = render(&zero(), "mangos-zero");
        for (service, port) in [("realmd", 3724), ("mangosd", 8085)] {
            let block = section(&text, service);
            let want = if service == "realmd" { "worldstone/vanilla-realm:latest" } else { "worldstone/vanilla-world:latest" };
            assert!(block.contains(&format!("image: \"{want}\"")), "{block}");
            assert!(block.contains("pull_policy: never"));
            assert!(block.contains(&format!("container_name: \"worldstone-mangos-zero-{service}\"")));
            assert!(block.contains(&format!("- \"127.0.0.1:{port}:{port}\"")), "published on this machine only: {block}");
            assert!(block.contains(&format!("exec 3<>/dev/tcp/127.0.0.1/{port}")), "healthy means the port accepts connections");
            assert!(block.contains("condition: service_healthy"), "nothing starts before the database is up");
        }
        assert!(section(&text, "realmd").contains("- \"/mangos/bin/realmd\"") && text.contains("- \"/worldstone/config/realmd.conf\""));
        assert!(section(&text, "mangosd").contains("- \"/worldstone/config/mangosd.conf\""));
    }

    #[test]
    fn the_database_runs_from_its_own_named_image_that_is_never_pulled_under_that_name() {
        let db = section(&render(&zero(), "mangos-zero"), "database");
        assert!(db.contains("image: \"worldstone/vanilla-database:11.4\"") && db.contains("pull_policy: never"), "{db}");
    }

    #[test]
    fn only_the_world_server_reads_client_data_and_has_a_console() {
        let text = render(&zero(), "mangos-zero");
        let (world, realm) = (section(&text, "mangosd"), section(&text, "realmd"));
        assert!(world.contains("stdin_open: true") && world.contains("source: gamedata"));
        assert!(!realm.contains("stdin_open") && !realm.contains("gamedata"));
        assert!(world.contains("stop_grace_period: \"120s\""));
        // The data volume is the extractor's own, referenced and never created here.
        assert!(text.contains("name: \"worldstone-mangos-zero-gamedata\"\n    external: true"), "{text}");
    }

    #[test]
    fn configuration_is_read_only_and_a_missing_folder_is_an_error_not_an_empty_one() {
        let text = render(&zero(), "mangos-zero");
        let world = section(&text, "mangosd");
        let config = &world[world.find("../Config/server").unwrap()..];
        assert!(config.contains("target: \"/worldstone/config\""));
        assert!(config[..config.find("../Logs/server").unwrap()].contains("read_only: true"));
        assert_eq!(world.matches("create_host_path: false").count(), 2);
    }

    #[test]
    fn server_arguments_come_from_the_recipe_one_per_line() {
        let text = render(&zero(), "mangos-zero");
        assert!(text.contains("      - \"--sql-mode=NO_ENGINE_SUBSTITUTION\""));
        assert!(text.contains("      - \"--character-set-server=utf8mb3\""));
    }

    #[test]
    fn writing_is_idempotent_and_creates_the_folder() {
        let dir = tempfile::tempdir().unwrap();
        let paths = crate::paths::Paths::at(dir.path().to_path_buf()).instance("mangos-zero").unwrap();
        let first = write(&paths, &zero(), "mangos-zero").unwrap();
        let stamp = std::fs::metadata(&first).unwrap().modified().unwrap();
        std::thread::sleep(std::time::Duration::from_millis(30));
        write(&paths, &zero(), "mangos-zero").unwrap();
        assert_eq!(std::fs::metadata(&first).unwrap().modified().unwrap(), stamp, "unchanged content is not rewritten");
        assert!(std::fs::read_to_string(first).unwrap().starts_with("# Generated by WorldStone"));
    }
}
